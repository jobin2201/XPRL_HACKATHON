def _examples(df: pd.DataFrame, cols, n=5):
    out = df.head(n)[cols].copy()
    for c in out.columns:
        if pd.api.types.is_datetime64_any_dtype(out[c]):
            out[c] = out[c].dt.strftime("%Y-%m-%d %H:%M:%S")
    return json.loads(out.to_json(orient="records"))


def payments(tx):
    """Successful payments between two different accounts (self-payments move no value between parties)."""
    return tx[(tx.tx_type == "Payment") & tx.destination.notna() & (tx.result == "tesSUCCESS") & (tx.destination != tx.account)]


def detect_rapid_forwarding(pay):
    """Match each outgoing payment to the latest incoming payment within 30 minutes."""
    inc = pay[["destination", "timestamp", "amount_usd", "account", "tx_hash"]].rename(
        columns={"destination": "acct", "timestamp": "in_ts", "amount_usd": "in_usd",
                 "account": "src", "tx_hash": "in_hash"})
    out = pay[["account", "timestamp", "amount_usd", "destination", "tx_hash"]].rename(
        columns={"account": "acct", "timestamp": "out_ts", "amount_usd": "out_usd",
                 "destination": "dst", "tx_hash": "out_hash"})
    inc = inc.sort_values("in_ts")
    out = out.sort_values("out_ts")
    m = pd.merge_asof(out, inc, left_on="out_ts", right_on="in_ts", by="acct",
                      tolerance=pd.Timedelta(minutes=30), direction="backward")
    m = m.dropna(subset=["in_hash"])
    m["ratio"] = m["out_usd"] / m["in_usd"]
    m = m[(m.ratio.between(0.5, 1.0)) & (m.src != m.dst) & (m.in_usd > 50)]
    m["delay_min"] = (m.out_ts - m.in_ts).dt.total_seconds() / 60
    return m


def chain_lengths(fwd):
    """Longest pass-through chain each account participates in (A -> B -> C -> ... via forwards)."""
    nxt = dict(zip(fwd.in_hash, fwd.out_hash))
    memo = {}

    def length(h, depth=0):
        if h in memo:
            return memo[h]
        if h not in nxt or depth > 50:
            return 0
        memo[h] = 1 + length(nxt[h], depth + 1)
        return memo[h]

    fwd = fwd.assign(chain=[length(h) for h in fwd.in_hash])
    return fwd.groupby("acct")["chain"].max()


def run_rules(tx):
    pay = payments(tx)
    hits = {}

    def add(acct, rule, evidence):
        hits.setdefault(acct, {})[rule] = evidence

    # structuring
    band = pay[pay.amount_usd.between(9000, 10000, inclusive="left")]
    for acct, g in band.groupby("account"):
        if len(g) >= 5:
            add(acct, "structuring", {"count": len(g), "total_usd": round(g.amount_usd.sum(), 2),
                                      "summary": f"{len(g)} payments between 9,000 and 9,999 USD",
                                      "examples": _examples(g, ["tx_hash", "timestamp", "destination", "amount_usd"])})

    # fan-out / fan-in per hour
    p = pay.assign(hour=pay.timestamp.dt.floor("h"))
    fo = p.groupby(["account", "hour"]).destination.nunique()
    for acct, s in fo[fo >= 10].groupby(level=0):
        hour = s.idxmax()[1]
        g = p[(p.account == acct) & (p.hour == hour)]
        add(acct, "fan_out", {"max_destinations_per_hour": int(s.max()), "hour": hour.strftime("%Y-%m-%d %H:00"),
                              "summary": f"{int(s.max())} distinct destinations in one hour",
                              "examples": _examples(g, ["tx_hash", "timestamp", "destination", "amount_usd"])})
    fi = p.groupby(["destination", "hour"]).account.nunique()
    for acct, s in fi[fi >= 10].groupby(level=0):
        hour = s.idxmax()[1]
        g = p[(p.destination == acct) & (p.hour == hour)]
        add(acct, "fan_in", {"max_sources_per_hour": int(s.max()), "hour": hour.strftime("%Y-%m-%d %H:00"),
                             "summary": f"{int(s.max())} distinct sources in one hour",
                             "examples": _examples(g, ["tx_hash", "timestamp", "account", "amount_usd"])})

    # round-tripping: A->B then B->A within 60 min at >= 90% of value
    a = pay[["account", "destination", "timestamp", "amount_usd", "tx_hash"]]
    b = a.rename(columns={"account": "destination", "destination": "account", "timestamp": "back_ts",
                          "amount_usd": "back_usd", "tx_hash": "back_hash"})
    rt = pd.merge_asof(a.sort_values("timestamp"), b.sort_values("back_ts"), left_on="timestamp",
                       right_on="back_ts", by=["account", "destination"], direction="forward",
                       tolerance=pd.Timedelta(minutes=60)).dropna(subset=["back_hash"])
    rt = rt[rt.back_usd >= 0.9 * rt.amount_usd]
    for acct, g in rt.groupby("account"):
        if len(g) >= 3:
            add(acct, "round_trip", {"count": len(g), "partners": int(g.destination.nunique()),
                                     "summary": f"{len(g)} payments returned within 60 min by {g.destination.nunique()} counterparties",
                                     "examples": _examples(g, ["tx_hash", "timestamp", "destination", "amount_usd", "back_usd"])})

    # rapid forwarding / peel chains
    fwd = detect_rapid_forwarding(pay)
    chains = chain_lengths(fwd)
    for acct, g in fwd.groupby("acct"):
        if len(g) >= 3:
            add(acct, "rapid_forward", {"count": len(g), "median_delay_min": round(g.delay_min.median(), 1),
                                        "longest_chain": int(chains.get(acct, 0)),
                                        "summary": f"{len(g)} payments passed on within 30 min (median {g.delay_min.median():.0f} min)",
                                        "examples": _examples(g.rename(columns={"out_hash": "tx_hash"}),
                                                              ["tx_hash", "in_ts", "src", "out_ts", "dst", "in_usd", "out_usd"])})

    # failed probing, odd hours, fee spikes, dust
    P = RULE_PARAMS.get(DATASET, RULE_PARAMS["official"])
    fee_min = max(P["fee_min_drops"], int(tx.fee.quantile(P["fee_quantile"]))) if P["fee_quantile"] else P["fee_min_drops"]
    RULE_THRESHOLDS["fee_min_drops"] = fee_min
    for acct, g in tx.groupby("account"):
        failed = g[g.result != "tesSUCCESS"]
        if P["failed_payments_to_others_only"]:
            # on Mainnet most failures are arbitrage bots (self-payments, offers, batches); probing means paying others
            failed = failed[(failed.tx_type == "Payment") & (failed.destination != failed.account)]
        if len(failed) >= P["failed_min"] and len(failed) / len(g) >= P["failed_share"]:
            add(acct, "failed_probing", {"failed": len(failed), "share": round(len(failed) / len(g), 3),
                                         "codes": failed.result.value_counts().to_dict(),
                                         "summary": f"{len(failed)} of {len(g)} transactions failed",
                                         "examples": _examples(failed, ["tx_hash", "timestamp", "destination", "result"])})
        night = g[g.timestamp.dt.hour < 5]
        if len(g) >= 10 and len(night) / len(g) >= 0.6:
            add(acct, "night_activity", {"night": len(night), "share": round(len(night) / len(g), 3),
                                         "summary": f"{len(night) / len(g):.0%} of activity between 00:00 and 05:00 UTC",
                                         "examples": _examples(night, ["tx_hash", "timestamp", "destination", "amount_usd"])})
        fee = g[g.fee >= fee_min]
        if len(fee):
            add(acct, "fee_spike", {"count": len(fee), "max_fee": int(fee.fee.max()),
                                    "summary": f"{len(fee)} transactions with fees up to {int(fee.fee.max()):,} drops",
                                    "examples": _examples(fee.sort_values("fee", ascending=False),
                                                          ["tx_hash", "timestamp", "fee", "result"])})
    dust = pay[pay.amount_usd < 1]
    for acct, g in dust.groupby("account"):
        if len(g) >= 10:
            add(acct, "dust", {"count": len(g), "summary": f"{len(g)} payments under 1 USD",
                               "examples": _examples(g, ["tx_hash", "timestamp", "destination", "amount_usd"])})
    return hits


def feature_deviations(X: pd.DataFrame, top=5):
    """Robust z-score of each feature against the median account."""
    med = X.median()
    mad = (X - med).abs().median().replace(0, np.nan)
    std = X.std().replace(0, np.nan)
    scale = (1.4826 * mad).fillna(std).fillna(1.0)
    z = ((X - med) / scale).clip(-50, 50)
    out = {}
    for i, row in z.iterrows():
        s = row.abs().sort_values(ascending=False).head(top)
        out[i] = [{"feature": f, "z": round(float(row[f]), 2), "value": round(float(X.loc[i, f]), 4),
                   "median": round(float(med[f]), 4)} for f in s.index]
    return out


def describe_rule(rule_id: str, default: str) -> str:
    """Rule text with this dataset's actual thresholds."""
    P = RULE_PARAMS.get(DATASET, RULE_PARAMS["official"])
    if rule_id == "fee_spike" and P["fee_quantile"]:
        return (f"Transactions paying {RULE_THRESHOLDS.get('fee_min_drops', P['fee_min_drops']):,}+ drops: the top "
                f"{(1 - P['fee_quantile']):.1%} of fees in this window (median fee is ~12 drops).")
    if rule_id == "failed_probing" and P["failed_payments_to_others_only"]:
        return (f"{P['failed_min']}+ failed payments to other accounts, making up at least {P['failed_share']:.0%} of activity "
                "(failed arbitrage, offers and batches are ignored).")
    return default


def tier(r):
    return "critical" if r >= 0.75 else "high" if r >= 0.5 else "medium" if r >= 0.3 else "low"


def main():
    data = load_all()
    tx = add_usd(data["transactions"], data["market_rates"])
    feats = pd.read_parquet(PROCESSED / "features.parquet").set_index("account")
    X = feats.select_dtypes("number").fillna(0.0)

    # Supervised score only where this dataset has labels. A model trained on synthetic data is not
    # applied to real accounts: its scores would look precise while meaning nothing.
    labels = pd.read_csv(RAW / "labels.csv").set_index("account")["is_suspicious"] if (RAW / "labels.csv").exists() else pd.Series(dtype=int)
    lab = labels[labels.index.isin(X.index)]
    supervised = lab.nunique() == 2 and (MODELS / "model.joblib").exists()
    metrics, imp = {}, pd.Series(dtype=float)
    if supervised:
        bundle = joblib.load(MODELS / "model.joblib")
        model, cols = bundle["model"], bundle["features"]
        Xm = feats.reindex(columns=cols, fill_value=0.0)
        model_score = pd.Series(model.predict_proba(Xm)[:, 1], index=X.index)
        # out-of-fold for labelled accounts, so there is no leakage
        cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
        oof = cross_val_predict(make_model(), Xm.loc[lab.index], lab, cv=cv, method="predict_proba")[:, 1]
        model_score.loc[lab.index] = oof
        metrics["cv_roc_auc"] = round(float(roc_auc_score(lab, oof)), 4)
        metrics["cv_pr_auc"] = round(float(average_precision_score(lab, oof)), 4)
        imp = pd.Series(model.feature_importances_, index=cols).sort_values(ascending=False)
    else:
        model_score = pd.Series(np.nan, index=X.index)

    # unsupervised anomaly score
    Xl = np.log1p(X.clip(lower=0))
    iso = IsolationForest(n_estimators=300, contamination="auto", random_state=SEED).fit(Xl)
    raw_anom = -iso.score_samples(Xl)
    anomaly = pd.Series(raw_anom, index=X.index).rank(pct=True)

    # rules
    disabled = DISABLED_RULES.get(DATASET, {})
    hits = {a: {r: ev for r, ev in h.items() if r not in disabled} for a, h in run_rules(tx).items()}
    hits = {a: h for a, h in hits.items() if h}
    rule_score = pd.Series({a: min(100, sum(RULES[r]["weight"] for r in h)) for a, h in hits.items()},
                           dtype=float).reindex(X.index, fill_value=0.0)

    if supervised:
        risk = (0.5 * model_score + 0.3 * rule_score / 100 + 0.2 * anomaly).clip(0, 1)
        formula = "risk = 0.5 x model + 0.3 x rule_score/100 + 0.2 x anomaly percentile"
    else:
        risk = (0.6 * rule_score / 100 + 0.4 * anomaly).clip(0, 1)
        formula = "risk = 0.6 x rule_score/100 + 0.4 x anomaly percentile (no labels, so no supervised model)"
    scores = pd.DataFrame({
        "model_score": model_score.round(4), "anomaly_score": anomaly.round(4),
        "anomaly_raw": np.round(raw_anom, 4), "rule_score": rule_score,
        "rules_triggered": [len(hits.get(a, {})) for a in X.index],
        "risk_score": risk.round(4),
    }, index=X.index)
    scores["tier"] = scores.risk_score.map(tier)
    scores["flagged"] = (scores.risk_score >= 0.4) | (scores.rule_score >= 30)
    scores["labelled"] = scores.index.isin(labels.index)
    scores["label"] = labels.reindex(scores.index)
    scores.index.name = "account"
    scores = scores.reset_index()

    devs = feature_deviations(X)
    alerts = {a: {"rules": hits.get(a, {}), "deviations": devs[a]} for a in X.index}

    hidden = PROCESSED / "hidden_test_labels.csv"
    if hidden.exists() and supervised:
        t = scores.merge(pd.read_csv(hidden), on="account")
        for col in ["model_score", "anomaly_score", "rule_score", "risk_score"]:
            metrics[f"holdout_test_roc_auc_{col}"] = round(float(roc_auc_score(t.is_suspicious, t[col])), 4)

    meta = {
        "dataset": DATASET,
        "model_version": MODEL_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "supervised_available": bool(supervised),
        "supervised_model": "RandomForestClassifier(n_estimators=400, min_samples_leaf=2, class_weight=balanced)" if supervised
        else "Not used: this dataset has no labels",
        "anomaly_model": f"IsolationForest(n_estimators=300) on log1p of {X.shape[1]} features",
        "risk_formula": formula,
        "flag_rule": "flagged if risk >= 0.40 or rule_score >= 30",
        "n_accounts": int(len(scores)), "n_labelled": int(scores.labelled.sum()),
        "metrics": metrics,
        "feature_importance": [{"feature": f, "importance": round(float(v), 4)} for f, v in imp.items()],
        "rules": [{"id": k, **v, "description": describe_rule(k, v["description"]), "disabled": disabled.get(k)} for k, v in RULES.items()],
        "rule_params": {**RULE_PARAMS.get(DATASET, RULE_PARAMS["official"]), **RULE_THRESHOLDS},
        "limitations": LIMITATIONS.get(DATASET, LIMITATIONS["official"]),
    }
    source = RAW / "source.json"
    if source.exists():
        meta["source"] = json.loads(source.read_text())

    PROCESSED.mkdir(parents=True, exist_ok=True)
    scores.to_parquet(PROCESSED / "scores.parquet", index=False)
    (PROCESSED / "alerts.json").write_text(json.dumps(alerts, default=str))
    (PROCESSED / "model_meta.json").write_text(json.dumps(meta, indent=2, default=str))

    print(f"scored {len(scores)} accounts, flagged {int(scores.flagged.sum())}")
    print("rule hits:", {r: sum(r in h for h in hits.values()) for r in RULES})
    print("metrics:", metrics)


if __name__ == "__main__":
    main()
