"""Phase 5 detection: transparent typology rules + Isolation Forest + the supervised model.

Every alert is explainable: each rule records the numbers and example transactions that fired it.

Outputs (data/processed):
  scores.parquet   one row per account with model / rule / anomaly / combined risk scores
  alerts.json      per-account rule hits with evidence, plus top feature deviations
  model_meta.json  model version, metrics, feature importance, rule catalogue, limitations
"""
import json
from datetime import datetime, timezone

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict

from features import add_usd
from load_data import DATASET, MODELS, PROCESSED, RAW, load_all
from train import make_model

MODEL_VERSION = f"0.4.0-{DATASET}"
SEED = 42

# Thresholds that depend on the network. The synthetic sample has a flat ~10-drop fee and rare failures;
# Mainnet has fee escalation under load and ~30% failed transactions (mostly arbitrage bots).
RULE_PARAMS = {
    "sample": dict(fee_min_drops=1000, fee_quantile=None, failed_min=5, failed_share=0.2, failed_payments_to_others_only=False),
    "official": dict(fee_min_drops=1000, fee_quantile=None, failed_min=5, failed_share=0.2, failed_payments_to_others_only=False),
    "mainnet": dict(fee_min_drops=1000, fee_quantile=0.999, failed_min=10, failed_share=0.5, failed_payments_to_others_only=True),
}
RULE_THRESHOLDS: dict = {}  # resolved at run time (e.g. the fee quantile), reported in model_meta.json

# Rules that make no sense for a dataset. Mainnet is a global, bot-heavy network sampled over minutes,
# so "time of day" says nothing about the account.
DISABLED_RULES = {"mainnet": {"night_activity": "Disabled: a short window of a 24/7 global ledger has no meaningful 'night'."}}

# Typology rules, modelled on common AML red flags (structuring, mule fan-out/fan-in,
# round-tripping, rapid pass-through / peel chains, failed-payment probing, odd-hour bursts, fee spikes, dust).
RULES = {
    "structuring": dict(name="Structuring", weight=35,
                        description="5+ payments valued just under the 10,000 USD reporting threshold (9,000-9,999)."),
    "fan_out": dict(name="Fan-out burst", weight=30,
                    description="Paid 10+ distinct destinations inside a single hour."),
    "fan_in": dict(name="Fan-in burst", weight=25,
                   description="Received from 10+ distinct sources inside a single hour."),
    "round_trip": dict(name="Round-tripping", weight=30,
                       description="3+ payments returned by the same counterparty within 60 minutes at 90%+ of value."),
    "rapid_forward": dict(name="Rapid forwarding / peel chain", weight=25,
                          description="3+ incoming payments forwarded on (50-100% of value) to someone else within 30 minutes."),
    "failed_probing": dict(name="Failed-payment probing", weight=15,
                           description="5+ failed transactions making up at least 20% of activity."),
    "night_activity": dict(name="Odd-hour activity", weight=10,
                           description="At least 60% of 10+ transactions sent between 00:00 and 05:00 UTC."),
    "fee_spike": dict(name="Fee spikes", weight=15,
                      description="Transactions paying 1,000+ drops in fees (the normal base fee is ~10-12 drops)."),
    "dust": dict(name="Dust spraying", weight=10,
                 description="10+ payments worth under 1 USD."),
}

